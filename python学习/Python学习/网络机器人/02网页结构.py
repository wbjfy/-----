# 一个网页是由三个部分组成，分别是:HTML、CSS、JS(JavaScript)
#     HTML:超文本标记语言，由一堆预设的标签(<h1>一级标签</h1>)构成。HTML负责网页的结构(页面元素和内容)
#     CSS:层叠样式表。CSS负责网页的表现(页面元素和外观、位置等样式，如颜色、大小等)
#     JS:全称为JavaScript，简称JS。负责网页的行为(交互效果)
# HTML：超文本标记语言
# 超文本：超越文本的限制，比普通文本更加强大。除了文字信息，还可以定义图片、音频、视频等内容
# 标记语言：由标签"<标签名>"构成语言
#     HTML标签都是预定好的。例如：使用<h1>展示标题，使用<img>展示图片，使用<video>展示视频。
#     HTML代码直接在浏览器中运行，HTML标签由浏览器解析