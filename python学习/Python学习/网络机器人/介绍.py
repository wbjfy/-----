# 爬虫：也称为网络爬虫，是一种按照一定的预设规则，自动浏览并抓取网络数据的程序或脚本
# 数据清洗：是指对采集到的袁术数据进行处理、修正、转换和标准化的过程，目的是让数据变得规范、准确

# robots协议
# robots协议也称为爬虫协议、爬虫规则，是指网站根目录下存放的一份文本文件robots.txt，用于告诉爬虫哪些页面可以抓取，哪些页面不能抓取
# 规则：
# 1、User-Agent:用户代理，通过该请求头的标识，确认爬虫身份
# 2、Disallow:不允许访问的资源
# 3、Allow:允许访问的资源
# 4、Sitemap:网站地图
# 5、Crawl-delay:访问的间隔时间