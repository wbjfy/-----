# 组包(Packing):将多个值合并到一个容器(元组，列表)中。
# 解包(Unpacking):将容器(元组，列表)解开成独立的元素，分别赋值给多个变量
# 定义元组，组包
t1 = (5,7,9,1)
t2 = 5,7,9,1
print(t2)
# 基础解包(变量数量要与容器元素数量一致)
a,b,c,d = t2
print(a,b,c,d)
# (*)扩展解包
x,*y,z = t2 # x为5，y为[7,9]，z为1
print(x,y,z)
s,*o = t2 # s为5，o为[7,9,1]
print(s,o)
*r,e = t2 # o为[5,7,9]，e为1
print(r,e)
# 说明：在元组解包时，*表示收集剩余的所有元素，允许我们处理不确定数量的元素（生成列表，以便于可以进一步的处理）。
# 数字交换也是元组的组包与解包
a = 1
b = 2
c = 3
# 此时左边时解包右边时组包
c,a,b = a,b,c
d = a,b,c
print(type(d))
print(a,b,c)