# 字符串的三种定义方式：
# 双引号定义
s1 = "Hello"
# 单引号定义
s2 = 'Python'
# 三引号定义(多行字符串)
s3 = """
    尊敬的客户：
            感谢您选择我们公司的产品
            我们奖会为您竭诚服务
            祝好 ~
"""
# 字符：是文本世界的基本单位，一个字母、一个数字、一个标点符号、一个汉字等都是一个字符
print(s1)
print(s2)
print(s3)
st1 = 'it\'s fine'
print(st1)
# 常见转义字符：
# \'   单引号     表示单引号'
# \"   双引号     表示双引号“
# \n   换行符     开始新的一行（换行）
# \t   制表符     增加缩进，缩进一个制表符（tab）的大小
print("It's very good")
print('"你好"')
print(123,"\n",456)