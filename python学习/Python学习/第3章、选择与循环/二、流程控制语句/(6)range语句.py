# 作用：生成指定规则的数字序列
# 用法一：range(end)    获取一个从0开始，到end结束的数字序列（不含end本身）例如：
for i in range(5):
    print(i)
# 用法二：range(start,end)   获取一个从start开始，到end结束的数字序列（不含end本身）例如：
for i in range(2,8):
    print(i)
# 用法三：range(start,end,step)   获取一个从start开始，到end结束的数字序列，step步长（不含end本身）例如：
for i in range(0,10,2):
    print(i)