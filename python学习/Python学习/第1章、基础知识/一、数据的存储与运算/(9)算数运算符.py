# 算数运算符是用于执行基本的数学运算的符号，作用于一个或多个操作数上的，并产生一个计算结果
# + 加法 - 减法 * 乘法 / 除法 // 整除 % 取余/求模 ** 幂指数
print("10 + 4 = ", 10 + 4)
print("10 - 4 = ", 10 - 4)
print("10 * 4 = ", 10 * 4)
print("10 / 4 = ", 10 / 4)
print("10 // 4 = ", 10 // 4)
print("10 % 4 = ", 10 % 4)
print("10 ** 4 = ", 10 ** 4)
#算数运算符的优先级 ** > * / // % > + -
print('0.1 + 10 / 4 ** 2 = ', 0.1 + 10 / 4 ** 2)
# 计算机底层是基于二进制机械能数据存储与处理，二进制是无法准确的表示所有的小数，因此设计到浮点数的运算，可能会出现精度损失
