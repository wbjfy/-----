#字面量：指程序中，直接书写的固定值（数据），就称字面量。
#字面量类型及书写格式
# 数字类型         整数（int）    浮点数/小数（float）
# 布尔（boll）     表达现实生活中的逻辑，真或假       True   False
# 字符串（str）     描述文本的一种数据类型
# 空值（None Type）表示空或无值，仅包含一个值None
# 数据容器         存储多项数据的容器         列表/元组/集合/字典
print(100)
print(3.14)
print(True)
print('Hello World')
print(None)
#布尔型本质也是整型
print(True + 1) #结果 2
